export function renderMarkdown(result: CorpusHReport) {
  return report.renderMarkdown(result)
    .replace('Generated by `pnpm exec tsx', 'Generated by `spice-heavy pnpm exec tsx')
    .replace('corpus-o rules, then corpus-l/i/h/f rules', 'unchanged corpus-l/i/h/f rules')
    .replace('Gap buckets apply the corpus-o rules in `lib.ts` first, then the corpus-l/i/h/f rules.', 'Gap buckets reuse corpus-l/i/h/f error classes unchanged.')
    .replace(/- Bounds: ngspice 600 s, spice-ts 120 s per fixture\./, '- Bounds: uniform 119 s owned engine process-group deadline; uniform 119 s comparison-process deadline. Measurement timeouts are not-compared, never engine failures or matches.')
    .replace(/\n## Transient fine-step reference \(#592\)[\s\S]*$/, '\n')
    + '\n## All ngspice-success parity gaps\n\n| Bucket | Count | IDs |\n|---|---|---|\n'
    + parityGaps(result.fixtures).map(b => `| ${b.bucket} | ${b.count} | ${b.ids.join(', ')} |`).join('\n')
    + '\n\n## Measurement boundary\n\nUnchanged corpus-j reduceRow and corpus-f metrics/thresholds. Detailed matched-point max/RMS absolute and relative metrics are in outcomes.json. Null means no comparison, not zero error. Identical original bytes for both engines; no fine-step adapted reference. Serial cold engine-group wall includes startup, adapter, parse/solve and export. No solver-only or speed-superiority claim. Before the MOS2/3/9 noise port and large-reference metric optimization: 16 matched, 3 failed, 4 not-compared. This rerun measures both changes with unchanged fixtures and comparison policy; remaining exclusions are still published. Aggregate refresh deferred to nightly. The classification/classCounts fields split legacy spice-ts-loss into unsupported and failed; legacy outcomes are retained unchanged. Issue links and exclusions: SOURCES.md.\n';
}
async function bounded(circuit: Circuit, engine: 'ngspice' | 'spiceTs') {
  const directory = await mkdtemp(resolve(tmpdir(), 'corpus-o-'));
  const output = resolve(directory, 'execution.bin');
  const start = performance.now();
  try {
    const result = await new Promise<{ code: number | null; timedOut: boolean }>((done, reject) => {
      const child = spawn(process.execPath, [...process.execArgv, fileURLToPath(import.meta.url), '--engine', engine, circuit.id, output], { detached: true, stdio: ['ignore', 'ignore', 'inherit'] });
      let timedOut = false;
      const timer = setTimeout(() => { timedOut = true; if (child.pid) { try { process.kill(-child.pid, 'SIGKILL'); } catch { /* exited */ } } }, 119_000);
      child.on('error', error => { clearTimeout(timer); reject(error); });
      child.on('close', code => { clearTimeout(timer); done({ code, timedOut }); });
    });
    const wallMs = performance.now() - start;
    if (result.code === 0 && !result.timedOut) return { run: deserialize(await readFile(output)) as ReferenceRun<PackedExecution>, wallMs };
    const error = result.timedOut ? 'owned engine group exceeded uniform 119 s deadline' : `engine exited ${result.code}`;
    return { run: { status: 'failed' as const, firstErrorLine: error, execution: { status: 'failed' as const, convergence: 'failed' as const, analyses: [], error } }, wallMs };
  } finally { await rm(directory, { recursive: true, force: true }); }
}
export const classification = (row: { outcome: string; spiceTs: { status: string } }) => row.spiceTs.status === 'unsupported' ? 'unsupported' : row.spiceTs.status === 'failed' ? 'failed' : row.outcome;
async function reduceBounded(circuit: Circuit, ng: ReferenceRun<PackedExecution>, spice: PackedExecution) {
  const directory = await mkdtemp(resolve(tmpdir(), 'corpus-o-metric-'));
  const input = resolve(directory, 'input.bin');
  const output = resolve(directory, 'output.bin');
  try {
    await writeFile(input, serialize({ circuit, ng, spice }));
    const result = await new Promise<{ code: number | null; timedOut: boolean }>((done, reject) => {
      const child = spawn(process.execPath, [...process.execArgv, fileURLToPath(import.meta.url), '--compare', input, output], { detached: true, stdio: ['ignore', 'ignore', 'inherit'] });
      let timedOut = false;
      const timer = setTimeout(() => { timedOut = true; if (child.pid) { try { process.kill(-child.pid, 'SIGKILL'); } catch { /* exited */ } } }, 119_000);
      child.on('error', error => { clearTimeout(timer); reject(error); });
      child.on('close', code => { clearTimeout(timer); done({ code, timedOut }); });
    });
    if (result.code === 0 && !result.timedOut) return deserialize(await readFile(output)) as ReturnType<typeof reduceRow>;
    // Preserve engine statuses. A measurement failure is not a simulator failure or a match.
    const row = reduceRow(circuit, ng, { ...spice, analyses: [] });
    return { ...row, spiceTs: { ...row.spiceTs, analyses: spice.analyses.map(a => `${a.type}:${a.grid.length}`) }, outcome: 'not-compared' as const,
      measurementError: result.timedOut ? 'uniform 119 s metric process-group deadline exceeded' : `metric process exited ${result.code}` };
  } finally { await rm(directory, { recursive: true, force: true }); }
}
async function main() {
  if (process.argv[2] === '--render') {
    await writeFile(`${ROOT}/README.md`, renderMarkdown(JSON.parse(await readFile(`${ROOT}/outcomes.json`, 'utf8')))); return;
  }
  if (process.argv[2] === '--compare') {
    const { circuit, ng, spice } = deserialize(await readFile(process.argv[3]));
    await writeFile(process.argv[4], serialize(reduceRow(circuit, ng, spice))); return;
  }
  const bytes = await readFile(`${ROOT}/manifest.json`);
  const manifest = JSON.parse(bytes.toString()) as Manifest;
  if (process.argv[2] === '--engine') {
    const circuit = manifest.circuits.find(c => c.id === process.argv[4]);
    if (!circuit) throw new Error('unknown fixture');
    const input = await readFile(circuit.localPath);
    if (hash(input) !== circuit.sha256) throw new Error('fixture hash mismatch');
    if (process.argv[3] !== 'ngspice' && process.argv[3] !== 'spiceTs') throw new Error('unknown engine');
    const run = process.argv[3] === 'ngspice' ? await runNgspicePacked(input, circuit) : await (async () => {
      const execution = await runBoundedSimulatePacked(input, { ...circuit, category: 'corpus-o', ngspice: { expectedStatus: 'pass' }, spiceTs: { expectedStatus: 'pass' } } as unknown as ClassicCircuit);
      return { status: execution.status, execution };
    })();
    await writeFile(process.argv[5], serialize(run)); return;
  }
  if (!/ngspice-47\b/.test(spawnSync('ngspice', ['--version'], { encoding: 'utf8' }).stdout)) throw new Error('requires ngspice-47');
  const coreTree = spawnSync('git', ['rev-parse', 'HEAD:packages/core'], { encoding: 'utf8' }).stdout.trim();
  const fixtures = process.argv[2] === '--resume' ? JSON.parse(await readFile(`${ROOT}/checkpoint.json`, 'utf8')) : [];
  if (process.argv[2] === '--resume' && (process.argv[3] !== coreTree || fixtures.some((r: { id: string; sha256: string }, i: number) => r.id !== manifest.circuits[i]?.id || r.sha256 !== manifest.circuits[i]?.sha256))) throw new Error('resume requires the original core tree and matching fixture prefix');
  for (const circuit of manifest.circuits.slice(fixtures.length)) {
    const ng = await bounded(circuit, 'ngspice');
    const spice = await bounded(circuit, 'spiceTs');
    const metricStart = performance.now();
    const reduced = await reduceBounded(circuit, ng.run, spice.run.execution);
    const metricProcessWallMs = performance.now() - metricStart;
    const row = { ...reduced, classification: classification(reduced), gapBucket: gapBucket(reduced.spiceTs.firstErrorLine, reduced.spiceTs.status) ?? null,
      runtime: { ngspiceChildWallMs: ng.wallMs, spiceTsChildWallMs: spice.wallMs, metricProcessWallMs } };
    fixtures.push(row);
    await writeFile(`${ROOT}/checkpoint.json`, JSON.stringify(fixtures, null, 2) + '\n');
    console.log(`${circuit.id} ${row.classification}: ng=${row.ngspice.status} ts=${row.spiceTs.status} ${row.spiceTs.firstErrorLine ?? ''}`);
  }
  const classCounts = Object.fromEntries(['matched', 'mismatch', 'unsupported', 'failed', 'not-compared'].map(key => [key, fixtures.filter(row => row.classification === key).length]));
  const base = { schemaVersion: 'spice-ts-corpus-o-outcomes/v1', sources: manifest.sources, manifestSha256: hash(bytes),
    coreTree: spawnSync('git', ['rev-parse', 'HEAD:packages/core'], { encoding: 'utf8' }).stdout.trim(),
    tools: { ngspice: 'ngspice-47', spiceTs: JSON.parse(await readFile('packages/core/package.json', 'utf8')).version, node: process.version },
    environment: { platform: platform(), release: release(), arch: arch(), cpu: cpus()[0]?.model },
    commands: { generate: `spice-heavy pnpm exec tsx ${ROOT}/parity.ts`, verify: `pnpm exec tsx --test ${ROOT}/corpus-o.test.ts`, ngspice: 'unchanged corpus-f runNgspicePacked on original bytes', spiceTs: 'unchanged corpus-f runBoundedSimulatePacked on original bytes' },
    policy: { input: 'byte-identical fixture for both engines', fixtureAdaptation: 'none', perCircuitToleranceTuning: false, matchThreshold: 0.01, matchRule: MATCH_RULE,
      deterministicHashExcludes: ['environment', 'tools.node', 'ngspice.analyses', 'spiceTs.analyses'], fineReference: 'none: no adapted deck', executionDeadlineMs: 119_000, metricDeadlineMs: 119_000,
      runtimeBoundary: 'serial cold owned engine group wall, not solver-only or warm runtime' }, ...report.summarize(fixtures), classCounts, fixtures, parityGaps: parityGaps(fixtures) };
  const result = { ...base, outcomeSha256: outcomeDigest(base as never) };
  await writeFile(`${ROOT}/outcomes.json`, JSON.stringify(result, null, 2) + '\n');
  await writeFile(`${ROOT}/README.md`, renderMarkdown(result as unknown as CorpusHReport));
  await rm(`${ROOT}/checkpoint.json`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch(error => { console.error(error); process.exitCode = 1; });
