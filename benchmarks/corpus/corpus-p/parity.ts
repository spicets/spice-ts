import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { outcomeDigest, runNgspicePacked, runBoundedSimulatePacked } from '../corpus-f/outcomes.js';
import type { ClassicCircuit } from '../classic/report.js';
import { reduceRow, type Manifest } from '../corpus-j/parity.js';
import { parityReport, type CorpusHReport } from '../corpus-h/parity.js';
import { gapBucket } from '../corpus-l/parity.js';
import { ROOT, hash } from './ingest.js';

// Reuse the existing owned-child runner, metrics and global 1% threshold unchanged.
const report = parityReport({ name: 'corpus-p', root: ROOT, scriptUrl: import.meta.url,
  title: '# corpus-p: public MNA-MAT and NetlistParse circuits (#1722)',
  earlierRules: 'corpus-l/i/h/f', gapIssues: {}, followUpIssues: [], gapBucket });
type Receipt = CorpusHReport & { classCounts: Record<string, number>; gapLinks: Record<string, string>; coreTree: string; sourceAdaptation: string; environment: CorpusHReport['environment'] & { perFixtureRuntimeMs?: Record<string, { ngspice: number; spiceTs: number }> } };
export function renderMarkdown(r: Receipt) {
  return `# corpus-p: MNA-MAT and NetlistParse (#1722)

Generated by \`spice-heavy pnpm exec tsx ${ROOT}/parity.ts --jobs 1\`.
Provenance, licences, upstream/adapted SHA256 and selection are in [SOURCES.md](SOURCES.md) and [manifest.json](manifest.json).

16 fixtures: 12 original MNA-MAT examples and four NetlistParse circuit/parser stress decks. No engine-success filter. Thirteen fixtures have mechanical title/OP wrappers; three are verbatim. Original element bytes are preserved. Both engines receive identical committed bytes, with no runtime fixture adaptation or per-circuit tuning. This is DC/OP coverage, not transient accuracy or a speed claim.

## Outcomes

- ngspice: ${JSON.stringify(r.totals.ngspice)}
- spice-ts: ${JSON.stringify(r.totals.spiceTs)}
- Outcomes: ${JSON.stringify(r.totals.outcomes)}
- Classified (spice-ts unsupported/failed split out): ${JSON.stringify(r.classCounts)}
- Outcome SHA256: \`${r.outcomeSha256}\`
- Core tree: \`${r.coreTree}\`

| ID | Outcome | ngspice | spice-ts | Worst normalized error | First error (ngspice / spice-ts) |
|---|---|---|---|---|---|
${r.fixtures.map(f => `| ${f.id} | ${f.outcome} | ${f.ngspice.status} | ${f.spiceTs.status} | ${f.worstNormalizedError ?? 'not compared'} | ${(f.ngspice.firstErrorLine ?? 'none') + ' / ' + (f.spiceTs.firstErrorLine ?? 'none')} |`).join('\n')}

## Measurement and losses

Unchanged corpus-f runner, corpus-h owned-child orchestration, 1% normalized peak threshold and existing signal floors. Full matched-point max/RMS absolute/relative metrics, environment, tool versions and per-fixture timings are in [outcomes.json](outcomes.json). Null is not zero error. Runtime includes child startup, parsing, solving and export on a shared host; no speed comparison is claimed.

All 13 ngspice-success decks match, so no ngspice-success gap issue is required. p-14 fails in ngspice, p-15 and p-16 fail or are unsupported in both engines; none is counted as a match. In particular, spice-ts success on p-14 is not evidence of correct extension semantics when the reference rejects the deck. The Xyce parser stress inputs remain unmodified and their losses are retained. Fine-step transient reference is not applicable to the 13 matched OP decks; the only transient stress deck is rejected by both engines.

Verify: \`pnpm exec tsx --test ${ROOT}/corpus-p.test.ts\`. Rerun with \`spice-heavy pnpm exec tsx ${ROOT}/parity.ts --check --jobs 1\`. Aggregate refresh is deferred to the nightly job; no aggregate policy or tolerance changed.
`;
}
async function main() {
  const version = spawnSync('ngspice', ['--version'], { encoding: 'utf8' });
  if (!/ngspice-47\b/.test(version.stdout ?? '')) throw new Error('requires ngspice-47');
  const check = process.argv.includes('--check');
  const previousBytes = check ? await readFile(`${ROOT}/outcomes.json`) : undefined;
  const previousMarkdown = check ? await readFile(`${ROOT}/README.md`) : undefined;
  const previous = previousBytes ? JSON.parse(previousBytes.toString()) as Receipt : undefined;
  try {
    if (!process.argv.includes('--render')) {
      const args = process.argv.slice(2).filter(arg => arg !== '--check');
      const child = spawnSync(process.execPath, [...process.execArgv, fileURLToPath(import.meta.url), '--raw', ...args], { stdio: 'inherit' });
      if (child.status !== 0) throw new Error(`corpus harness exited ${child.status}`);
    }
    const r = JSON.parse(await readFile(`${ROOT}/outcomes.json`, 'utf8')) as Receipt;
    if (!process.argv.includes('--render')) {
      // The summary runner omits full signal metrics. Remeasure identical bytes with
      // the existing packed runner/reducer and retain max/RMS metrics plus cold wall time.
      const manifest = JSON.parse(await readFile(`${ROOT}/manifest.json`, 'utf8')) as Manifest;
      r.environment.perFixtureRuntimeMs = {};
      for (const [i, circuit] of manifest.circuits.entries()) {
        const input = await readFile(circuit.localPath);
        if (hash(input) !== circuit.sha256) throw new Error(`fixture hash mismatch: ${circuit.id}`);
        const start = performance.now();
        const ng = await runNgspicePacked(input, circuit);
        const middle = performance.now();
        const spice = await runBoundedSimulatePacked(input, { ...circuit, category: 'corpus-p', ngspice: { expectedStatus: 'pass' }, spiceTs: { expectedStatus: 'pass' } } as unknown as ClassicCircuit);
        r.environment.perFixtureRuntimeMs[circuit.id] = { ngspice: middle - start, spiceTs: performance.now() - middle };
        const detailed = reduceRow(circuit, ng, spice);
        if (detailed.outcome !== r.fixtures[i].outcome) throw new Error(`summary/detail outcome drift: ${circuit.id}`);
        r.fixtures[i] = detailed;
      }
      Object.assign(r, report.summarize(r.fixtures));
    }
    r.classCounts = {};
    r.gapLinks = {};
    for (const f of r.fixtures) {
      const key = f.spiceTs.status === 'unsupported' ? 'unsupported' : f.spiceTs.status === 'failed' ? 'failed' : f.outcome;
      r.classCounts[key] = (r.classCounts[key] ?? 0) + 1;
      if (f.ngspice.status === 'success' && f.outcome !== 'matched') throw new Error(`untriaged ngspice-success gap: ${f.id}`);
    }
    r.coreTree = spawnSync('git', ['rev-parse', 'HEAD:packages/core'], { encoding: 'utf8' }).stdout.trim();
    r.sourceAdaptation = '13 committed mechanical OP wrappers, 3 verbatim decks; manifest records reversible wrappers and both hashes. policy.fixtureAdaptation=none refers to runtime input.';
    r.outcomeSha256 = outcomeDigest(r as never);
    if (previous && previous.outcomeSha256 !== r.outcomeSha256) throw new Error('corpus-p outcomes drifted');
    if (previousMarkdown && previousMarkdown.toString() !== renderMarkdown(r)) throw new Error('corpus-p README drifted');
    await writeFile(`${ROOT}/outcomes.json`, JSON.stringify(r, null, 2) + '\n');
    await writeFile(`${ROOT}/README.md`, renderMarkdown(r));
  } finally {
    // The shared CLI writes artifacts; a check must leave the committed receipt untouched.
    if (previousBytes && previousMarkdown) {
      await writeFile(`${ROOT}/outcomes.json`, previousBytes);
      await writeFile(`${ROOT}/README.md`, previousMarkdown);
    }
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--corpus-p-fixture-child') report.cli();
  else if (process.argv[2] === '--raw') { process.argv.splice(2, 1); report.cli(); }
  else main().catch(error => { console.error(error); process.exitCode = 1; });
}
