import { readFile, writeFile } from 'node:fs/promises';
import { renderMarkdown, ROOT, summarize } from './parity.js';
import type { CorpusHReport } from '../corpus-h/parity.js';
async function main() {
  const report = JSON.parse(await readFile(`${ROOT}/part2-outcomes.json`, 'utf8'));
  const historical = JSON.parse(await readFile(`${ROOT}/outcomes.json`, 'utf8'));
  const combined = summarize([...historical.fixtures, ...report.fixtures]).totals.outcomes;
  const counts = report.totals;
  const metrics = report.fixtures.flatMap((row: any) => row.comparisons.flatMap((comparison: any) =>
    Object.entries(comparison.metrics.signals).filter(([, metric]: any) => metric.status === 'compared').map(([signal, metric]: any) =>
      `| ${row.id} | ${comparison.analysis} ${signal} | ${metric.sampleCount} | ${metric.absoluteError.max} | ${metric.absoluteError.rms} | ${metric.relativeError.max ?? 'unavailable'} | ${metric.relativeError.rms ?? 'unavailable'} |`)));
  const combinedWall = report.actualCumulativeChildWallMs;
  const display = { ...report, policy: { ...report.policy, deterministicHashExcludes: ['environment', 'tools.node', 'ngspice.analyses', 'spiceTs.analyses'] },
    gapBuckets: report.gapBuckets.map((bucket: any) => ({ ...bucket, issue: bucket.ids.includes('j-19') ? 'https://github.com/spicets/spice-ts/issues/1633 (j-19)' : bucket.issue })) };
  const markdown = renderMarkdown(display as CorpusHReport)
    .replace('# corpus-j: partial novel source survey (#940)', '# corpus-j part 2: nine original fixtures (#940)')
    .replace('Generated by `pnpm exec tsx benchmarks/corpus/corpus-j/parity.ts`', 'Generated by `pnpm exec tsx benchmarks/corpus/corpus-j/render-part2.ts`')
    .replace('op/dc/ac/tran/pz/noise/disto plot', 'op/dc/ac/tran/pz/noise/disto/sp/sens plot')
    .replace('- none\n', '- https://github.com/spicets/spice-ts/issues/1633: AC sensitivity without explicit AC excitation (j-19).\n');
  await writeFile(`${ROOT}/PART2.md`, markdown + `
## Delivery and export limits

Nine original part2 input hashes bring the manifest to 20. Historical j-1..j-11 outcomes.json and wall.jsonl remain byte-identical to #947; their 11 both-failed outcomes are not upgraded by this refresh. Part 2 has ${counts.ngspice.success} ngspice raw successes, ${counts.outcomes.matched} matched rows, ${counts.outcomes['spice-ts-loss']} spice-ts-only loss and ${counts.outcomes['both-failed']} both-failed rows. The combined 20-row catalogue therefore has ${combined.matched} matched, ${combined['spice-ts-loss']} spice-ts-only losses and ${combined['both-failed']} both-failed. Input-hash novelty is not a claim of nine novel topology families.

Control decks use unchanged corpus-f runControlReference instead of batch-only raw capture: a source/write wrapper receives original bytes, defers quit/exit and exports all retained plots by ID for each declared type. No circuit, analysis or tolerance is rewritten. All six j-14 DC plots, including nested TEMP sweeps, are compared. Success here requires actual raw vectors. DISPLAY is removed by the control wrapper.

The matched criterion and breakpoint-aware/linear metrics are unchanged. Null/empty metrics mean unavailable, never measured zero. Fine-step adapted references are not run. Cold engine groups are serial, 19 s execution deadline/20 s boundary; the persisted cumulative budget includes historical attempts, including an initial refresh before building the core package. Measured combined child wall: ${combinedWall} ms. No speed superiority claim. No simulator change: this refresh uses the recorded coreTree on current main (#1632), not a before/after solver performance comparison. Nightly #855 owns aggregate incorporation.

## Issue deduplication

Resolved historical gaps and the remaining loss:

- j-14: [#956](https://github.com/spicets/spice-ts/issues/956), nested DC TEMP source lookup, is closed; all six DC plots now match.
- j-16: [#957](https://github.com/spicets/spice-ts/issues/957), .title metadata, is closed; all seven OP signals now match.
- j-17/j-18/j-20: both engines reject original .backanno; no spice-ts-only issue.
- j-19: ngspice-47 now succeeds with a 31-point sensitivity plot (historical receipt: PMOS Nsub < Ni). spice-ts still rejects the missing AC source in .sens, so this is now a spice-ts-only loss, tracked by [#1633](https://github.com/spicets/spice-ts/issues/1633). The historical reference difference is not attributed to a specific change. Related closed #1389 covers explicit DC/AC values with transient waveforms, not absent AC excitation.

The remaining loss has label bug and milestone M1 Correctness parity. No simulator fixes or fixture changes in this refresh.

## Matched-point metrics

All compared signals below; relative metrics exclude zero reference samples under the unchanged shared rule. Full grid exclusions, missing signals and linear-interpolation metrics are in part2-outcomes.json.

| Fixture | Signal | Points | Max abs | RMS abs | Max rel | RMS rel |
|---|---|---|---|---|---|---|
${metrics.join('\n')}

## Commands

    pnpm install --frozen-lockfile
    pnpm build && pnpm lint
    spice-heavy pnpm exec tsx benchmarks/corpus/corpus-j/part2.ts
    pnpm exec tsx benchmarks/corpus/corpus-j/render-part2.ts
    pnpm exec tsx --test benchmarks/corpus/corpus-j/corpus-j.test.ts benchmarks/corpus/corpus-j/part2.test.ts
    spice-heavy pnpm test

Source ingestion is append-part2.ts against the original 11-row manifest and pinned checkouts documented in SOURCES.md; never rerun legacy select.ts/parity.ts over the appended manifest. Offline tests verify fixture/licence hashes, dedup, manifest reconstruction, all outcome rows, metric availability and cumulative wall accounting. Required exact-head CI and independent review govern publication; local logs do not replace that gate.
`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
