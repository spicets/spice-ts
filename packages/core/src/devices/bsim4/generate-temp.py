#!/usr/bin/env python3
"""Generate the ordered static TEMPMOD=0/silicon kernel from clean pinned ngspice.
Usage: python3 generate-temp.py SOURCE [--check]. ECL-2.0, like its source.
The public wrapper owns guards, immutable outputs, b4geo and DIOMOD=1 bridging.
"""
import argparse
import re
import subprocess
from pathlib import Path

SHA = 'a80f6e3e95d51534905b1f23410a951802666656'
# No cache/list allocation, charge-only capacitance, inactive material/stress,
# MOBMOD=3, body/gate network, DIOMOD=0/2 or trap-assisted junction paths.
RANGES = [(97, 142), (169, 171), (177, 177), (179, 196), (200, 213),
          (224, 227), (231, 276), (332, 369), (372, 388),
          (454, 476), (485, 485), (494, 494), (503, 503), (512, 512),
          (522, 1183), (1185, 1213), (1269, 1288), (1290, 1299),
          (1301, 1314), (1324, 1348), (1359, 1373), (1376, 1379), (1401, 1405),
          (1410, 1412), (1415, 1417),
          (1420, 1499), (1501, 1572), (1649, 1652), (1697, 1701),
          (1758, 1794), (2393, 2394)]


def generate(source: Path) -> str:
    def git(*args):
        return subprocess.check_output(['git', '-C', str(source), *args], text=True).strip()
    assert git('rev-parse', 'HEAD') == SHA
    assert not git('status', '--porcelain', '--untracked-files=all'), 'Source must be clean'
    directory = source / 'src/spicelib/devices/bsim4'
    text = (directory / 'b4temp.c').read_text()
    lines = text.splitlines()
    table = re.sub(r'/\*.*?\*/', '', (directory / 'b4.c').read_text(), flags=re.S)
    setter = re.sub(r'/\*.*?\*/', '', (directory / 'b4mpar.c').read_text(), flags=re.S)
    entries = {}
    for name, identifier in re.findall(r'\b(?:IOP\w*|IP\w*)\(\s*"([^"]+)"\s*,\s*(BSIM4_MOD_\w+)', table):
        entries.setdefault(identifier, name)
    fields = {'type': 'type', 'v48intVersion': 'v48intversion'}
    cases = list(re.finditer(r'\bcase\s+(BSIM4_MOD_\w+)\s*:', setter))
    for index, case in enumerate(cases):
        block = setter[case.end():cases[index + 1].start() if index + 1 < len(cases) else len(setter)]
        assigned = re.findall(r'mod->BSIM4(\w+)\s*=(?!=)', block)
        assigned = [field for field in assigned if not field.endswith('Given')]
        if assigned[0] != 'type':
            fields[assigned[0]] = entries[case[1]]
    body = ''
    for first, last in RANGES:
        block = '\n'.join(lines[first - 1:last])
        # Omit stdout/stderr warnings, not their numerical clamp/default logic.
        block = re.sub(r'\b(?:fprintf|printf)\s*\((?:[^;"\']|"(?:[^"\\]|\\.)*")*\);', '', block, flags=re.S)
        # Warnings with no surviving statement in an if body must remain no-ops.
        block = re.sub(r'(if\s*\([^\n]+\))\s*(?=if|\})', r'\1 {}\n', block)
        body += f'\n  // b4temp.c:{first}-{last}\n' + block + '\n'
    # Preserve comments before token replacement.
    comments = []
    def save(match):
        comments.append(match[0])
        return f'__COMMENT_{len(comments)-1}__'
    body = re.sub(r'/\*.*?\*/', save, body, flags=re.S)
    model_extras = sorted({f for f in re.findall(r'model->BSIM4(\w+)', body) if f not in fields and not f.endswith('Given')})
    size_fields = sorted(set(re.findall(r'pParam->BSIM4(\w+)', body)))
    instance_fields = sorted(set(re.findall(r'here->BSIM4(\w+)', body)) - {'nf', 'l', 'w', 'delvto', 'mulu0'})
    def model_member(match):
        f = match[1]
        if f.endswith('Given'):
            return f"given.has('{fields[f[:-5]]}')"
        return 'model.' + fields.get(f, f)
    body = re.sub(r'model->BSIM4(\w+)', model_member, body)
    body = re.sub(r'pParam->BSIM4(\w+)', r'pParam.\1', body)
    body = re.sub(r'here->BSIM4(\w+)', r'here.\1', body)
    body = body.replace('ckt->CKTtemp', 'Temp')
    body = re.sub(r'\bdouble\s+(\w+)\s*=', r'let \1 =', body)
    body = re.sub(r'\b(?:fabs|ABS)\(', 'Math.abs(', body)
    for name in ['pow', 'log', 'sqrt', 'exp', 'atan']:
        body = re.sub(r'\b' + name + r'\(', 'Math.' + name + '(', body)
    body = body.replace('NMOS', '1').replace('PMOS', '-1')
    body = re.sub(r'DEXP\((\w+),\s*(\w+)\);', r'\2 = dexp(\1);', body)
    assert not re.search(r'->|\b(?:printf|fprintf|BSIM4\w+|ckt|double)\b', body), 'Untranslated tokens'
    body = re.sub(r'__COMMENT_(\d+)__', lambda m: comments[int(m[1])], body)
    # Preserve ordering with a predictable readable indentation, no C formatting dependency.
    body = '\n'.join('  ' + line.strip() if line.strip() else '' for line in body.splitlines())
    header = text[:text.index('#include')]
    output = header + f'\n// Modified/ported to TypeScript by spice-ts. Generated by generate-temp.py.\n// Pinned source {SHA}. Warning output omitted, numerical branches preserved.\n'
    output += "import type { Bsim4ModelValues, Bsim4ModelParameter } from './params.js';\nimport type { Bsim4InstanceValues } from './instance-params.js';\n"
    def union(items):
        return ' | '.join(repr(item) for item in items)
    output += "import { applyLod } from './lod.js';\n"
    output += f'export type Bsim4TemperatureModel = Bsim4ModelValues & Record<{union(model_extras)}, number>;\n'
    output += f'export type Bsim4Size = Record<{union(size_fields)}, number>;\n'
    output += f'export type Bsim4TemperatureInstance = {{ -readonly [K in keyof Bsim4InstanceValues]: Bsim4InstanceValues[K] }} & Record<{union(instance_fields)}, number>;\n'
    output += '''const KboQ = 8.617087e-5, EPS0 = 8.85418e-12, EPSSI = 1.03594e-10;
const PI = 3.141592654, Charge_q = 1.60219e-19;
const MIN_EXP = 1.713908431e-15, MAX_EXP = 5.834617425e14, EXP_THRESHOLD = 34;
// ngspice const.h uses these fixed historical limiting constants.
const CONSTvt0 = 1.38064852e-23 * 300.15 / 1.6021766208e-19, CONSTroot2 = 1.4142135623730951;
function dexp(A: number): number {
  return A > EXP_THRESHOLD ? MAX_EXP * (1 + A - EXP_THRESHOLD)
    : A < -EXP_THRESHOLD ? MIN_EXP : Math.exp(A);
}
/** Internal ordered kernel. Caller must enforce static baseline selectors and validate outputs. */
export function applyTemperature(
  model: Bsim4TemperatureModel, given: ReadonlySet<Bsim4ModelParameter>,
  here: Bsim4TemperatureInstance, pParam: Bsim4Size, Temp: number,
): void {
  let T0 = 0, T1 = 0, T2 = 0, T3 = 0, T4 = 0, T5 = 0, T8 = 0, T9 = 0, T10 = 0;
  let tmp = 0, tmp1 = 0, tmp2 = 0, Lnew = 0, Wnew = 0;
  let Tnom = 0, TRatio = 0, Vtm0 = 0, Eg0 = 0, Eg = 0, ni = 0;
  let epsrox = 0, toxe = 0, epssub = 0, Inv_L = 0, Inv_W = 0, Inv_LW = 0, PowWeffWr = 0;
  const delTemp = Temp - model.tnom;
'''
    body = body.replace('  here.k2 = pParam.k2;\n',
                        '  here.k2 = pParam.k2;\n\n  applyLod(model, here, pParam, Temp, Lnew, Wnew);\n')
    output += body + '\n}\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.source)
    target = Path(__file__).resolve().parent / 'temperature-kernel.ts'
    if args.check:
        assert target.read_text() == content, 'Generated kernel differs'
    else:
        target.write_text(content)
    print('Verified' if args.check else 'Generated', target.name)

if __name__ == '__main__':
    main()
