#!/usr/bin/env python3
"""Generate the static channel equations, preserving pinned b4ld ordering/ECL-2.0.
Usage: python3 generate-load.py SOURCE [--check]. No dynamic or terminal stamps.
"""
import argparse
import re
import subprocess
from pathlib import Path

SHA = 'a80f6e3e95d51534905b1f23410a951802666656'
RANGES = [(1004, 2189), (2527, 2921)]


def generate(source: Path) -> str:
    def git(*args):
        return subprocess.check_output(['git', '-C', str(source), *args], text=True).strip()
    assert git('rev-parse', 'HEAD') == SHA
    assert not git('status', '--porcelain', '--untracked-files=all'), 'Source must be clean'
    directory = source / 'src/spicelib/devices/bsim4'
    text = (directory / 'b4ld.c').read_text()
    lines = text.splitlines()
    table = re.sub(r'/\*.*?\*/', '', (directory / 'b4.c').read_text(), flags=re.S)
    setter = re.sub(r'/\*.*?\*/', '', (directory / 'b4mpar.c').read_text(), flags=re.S)
    entries = {}
    for name, identifier in re.findall(r'\b(?:IOP\w*|IP\w*)\(\s*"([^"]+)"\s*,\s*(BSIM4_MOD_\w+)', table):
        entries.setdefault(identifier, name)
    fields = {'type': 'type', 'v48intVersion': 'v48intversion'}
    cases = list(re.finditer(r'\bcase\s+(BSIM4_MOD_\w+)\s*:', setter))
    for index, case in enumerate(cases):
        block = setter[case.end():cases[index + 1].start() if index + 1 < len(cases) else len(setter)]
        assigned = [f for f in re.findall(r'mod->BSIM4(\w+)\s*=(?!=)', block) if not f.endswith('Given')]
        if assigned[0] != 'type':
            fields[assigned[0]] = entries[case[1]]
    body = '\n'.join(f'\n// b4ld.c:{first}-{last}\n' + '\n'.join(lines[first - 1:last]) for first, last in RANGES)
    comments = []
    def save(match):
        comments.append(match[0])
        return f'__COMMENT_{len(comments)-1}__'
    body = re.sub(r'/\*.*?\*/|//[^\n]*', save, body, flags=re.S)
    model_extras = sorted({f for f in re.findall(r'model->BSIM4(\w+)', body) if f not in fields and not f.endswith('Given')})
    size_fields = sorted(set(re.findall(r'pParam->BSIM4(\w+)', body)))
    here_fields = sorted(set(re.findall(r'here->BSIM4(\w+)', body)))
    def model_member(match):
        f = match[1]
        if f.endswith('Given'):
            return f"given.has('{fields[f[:-5]]}')"
        return 'model.' + fields.get(f, f)
    body = re.sub(r'model->BSIM4(\w+)', model_member, body)
    body = re.sub(r'pParam->BSIM4(\w+)', r'pParam.\1', body)
    body = re.sub(r'here->BSIM4(\w+)', r'here.\1', body)
    body = body.replace('ckt->CKTtemp', 'Temp')
    body = re.sub(r'BSIM4polyDepletion\((.*?), &(\w+), &(\w+)\);', r'[\2, \3] = polyDepletion(\1);', body)
    body = re.sub(r'DEXP\((\w+),\s*(\w+),\s*(\w+)\);', r'[\2, \3] = dexp(\1);', body)
    body = re.sub(r'\b(?:fabs|ABS)\(', 'Math.abs(', body)
    for name in ['pow', 'log', 'sqrt', 'exp']:
        body = re.sub(r'\b' + name + r'\(', 'Math.' + name + '(', body)
    declarations = re.sub(r'/\*.*?\*/|//[^\n]*', '', '\n'.join(lines[100:257]), flags=re.S)
    variables = []
    for group in re.findall(r'\bdouble\s+([^;]+);', declarations):
        for declaration in group.split(','):
            name = declaration.split('=')[0].strip()
            if re.fullmatch(r'\w+', name) and re.search(r'(?<![.\w])' + name + r'\b', body):
                variables.append(name)
    variables = sorted(set(variables) - {'vgs', 'vds', 'vbs', 'vgd', 'vbd'})
    assert not re.search(r'->|\b(?:BSIM4\w+|ckt|double)\b', body), 'Untranslated tokens'
    body = re.sub(r'__COMMENT_(\d+)__', lambda m: comments[int(m[1])], body)
    body = '\n'.join('  ' + line.strip() if line.strip() else '' for line in body.splitlines())
    union = lambda items: ' | '.join(repr(item) for item in items)
    header = text[:text.index('#include')]
    output = header + f'\n// Modified/ported to TypeScript by spice-ts. Generated by generate-load.py.\n// Source {SHA}; static-only caller must enforce selector and check contracts.\n'
    # A legal comment survives esbuild bundling without editing build/package
    # metadata. Keep the original source header verbatim above; ship its notice
    # contents and the full licence in every bundle that includes this kernel.
    licence = (Path(__file__).resolve().parent / 'LICENSE-ECL-2.0').read_text()
    notice = header.replace('/*', '').replace('*/', '')
    output += '/*! @license\n' + notice + '\nModified/ported to TypeScript by spice-ts.\n' + licence + '\n*/\n'
    output += "import type { Bsim4TemperatureModel, Bsim4Size } from './temperature-kernel.js';\nimport type { Bsim4StaticInstance } from './temp.js';\nimport type { Bsim4ModelParameter } from './params.js';\n"
    output += f'export type Bsim4LoadModel = Bsim4TemperatureModel & Record<{union(model_extras)}, number>;\n'
    output += f'export type Bsim4LoadSize = Bsim4Size & Record<{union(size_fields)}, number>;\n'
    output += f'export type Bsim4LoadInstance = Bsim4StaticInstance & Record<{union(here_fields)}, number>;\n'
    output += '''const MAX_EXP = 5.834617425e14, MIN_EXP = 1.713908431e-15, EXP_THRESHOLD = 34;
const EPS0 = 8.85418e-12, EPSSI = 1.03594e-10, Charge_q = 1.60219e-19, MM = 3;
// Historical ngspice const.h CHARGE, not the BSIM-local Charge_q.
const CHARGE = 1.6021766208e-19, DELTA_3 = 0.02;
function dexp(A: number): [number, number] {
  if (A > EXP_THRESHOLD) return [MAX_EXP * (1 + A - EXP_THRESHOLD), MAX_EXP];
  if (A < -EXP_THRESHOLD) return [MIN_EXP, 0];
  const B = Math.exp(A); return [B, B];
}
// b4ld.c:5413-5431.
function polyDepletion(phi: number, ngate: number, epsgate: number, coxe: number, Vgs: number): [number, number] {
  if (ngate > 1e18 && ngate < 1e25 && Vgs > phi && epsgate !== 0) {
    const T1 = 1e6 * CHARGE * epsgate * ngate / (coxe * coxe), T8 = Vgs - phi;
    const T4 = Math.sqrt(1 + 2 * T8 / T1), T2 = 2 * T8 / (T4 + 1), T3 = 0.5 * T2 * T2 / T1;
    const T7 = 1.12 - T3 - 0.05, T6 = Math.sqrt(T7 * T7 + 0.224), T5 = 1.12 - 0.5 * (T7 + T6);
    return [Vgs - T5, 1 - (0.5 - 0.5 / T4) * (1 + T7 / T6)];
  }
  return [Vgs, 1];
}
export function applyLoad(model: Readonly<Bsim4LoadModel>, given: ReadonlySet<Bsim4ModelParameter>,
  here: Bsim4LoadInstance, pParam: Readonly<Bsim4LoadSize>, Temp: number,
  vgs: number, vds: number, vbs: number): number {
  const vgd = vgs - vds, vbd = vbs - vds;
'''
    for start in range(0, len(variables), 6):
        output += '  let ' + ', '.join(v + ' = 0' for v in variables[start:start + 6]) + ';\n'
    output += body + '\n  return cdrain;\n}\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.source)
    target = Path(__file__).resolve().parent / 'load-kernel.ts'
    if args.check:
        assert target.read_text() == content, 'Generated kernel differs'
    else:
        target.write_text(content)
    print('Verified' if args.check else 'Generated', target.name)


if __name__ == '__main__':
    main()
